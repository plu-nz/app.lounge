const dicts: Record<string, Dict> = { en, pt, es };
export const languages = ['en', 'pt', 'es'] as const;
export const languageNames: Record<string, string> = { en: 'English', pt: 'Português', es: 'Español' };

function systemLanguage(): string {
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.toLowerCase().split('-')[0];
    if (base in dicts) return base;
  }
  return 'en';
}

const [lang, setLangSignal] = createSignal(systemLanguage());
export { lang };

/** setLanguage applies a preference; an empty value follows the system. */
export function setLanguage(pref: string) {
  const next = pref && pref in dicts ? pref : systemLanguage();
  setLangSignal(next);
  document.documentElement.lang = next;
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[lang()][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function typeName(type: string): string {
  const key = `type.${type}` as Key;
  return key in en ? t(key) : type.charAt(0).toUpperCase() + type.slice(1);
}
